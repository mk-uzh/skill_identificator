"""Build the person cards of the study tool from silver tables (facts only).

Writes runs/<project>_people.candidate.json. Nothing here is generated by a
model: every number is counted, every area name comes from the issue
components of the person's own changes.
"""
from __future__ import annotations

import argparse
import json
from collections import Counter, defaultdict
from datetime import datetime, timezone

from common import ensure_runs, load_config, project_cfg, read_csv, silver_dir

MONTHS = ["January", "February", "March", "April", "May", "June", "July",
          "August", "September", "October", "November", "December"]


def month_year(ts: str) -> str:
    return f"{MONTHS[int(ts[5:7]) - 1]} {ts[:4]}"


def join(items: list[str]) -> str:
    if len(items) <= 1:
        return "".join(items)
    return ", ".join(items[:-1]) + " and " + items[-1]


def build(project: str) -> list[dict]:
    cfg = load_config()
    people = cfg["study_developers"]
    d = silver_dir(project)
    commits = [c for c in read_csv(d / "slv_commit.csv") if c["in_window"] == "1" and c["is_merge"] != "1"]
    prs = read_csv(d / "slv_pull_request.csv")
    reviews = [r for r in read_csv(d / "slv_review.csv") if r["is_bot"] != "1"]
    comps = defaultdict(list)
    for r in read_csv(d / "slv_issue_component.csv"):
        comps[r["issue_key"]].append(r["component"])
    pr_author = {p["pr_number"]: p["author_dev_id"] for p in prs}
    sent_back = defaultdict(set)
    for r in reviews:
        if r["state"] == "CHANGES_REQUESTED" and pr_author.get(r["pr_number"]):
            sent_back[pr_author[r["pr_number"]]].add(r["pr_number"])
    own_prs = Counter(p["author_dev_id"] for p in prs)

    out = []
    for dev in people:
        mine = sorted((c for c in commits if c["dev_id"] == dev), key=lambda c: c["authored_at"])
        revs = {r["pr_number"] for r in reviews
                if r["reviewer_dev_id"] == dev and pr_author.get(r["pr_number"]) not in (None, "", dev)}
        n_c, n_r = len(mine), len(revs)
        if not mine:
            continue
        first, last = mine[0]["authored_at"], mine[-1]["authored_at"]
        areas = Counter(a for c in mine for a in set(comps.get(c["issue_key"], [])))
        top = [a for a, _ in areas.most_common(3)]
        linked = sum(1 for c in mine if c["has_issue"] == "1")
        facts = [
            f"{n_c} change{'s' if n_c != 1 else ''}, the first one in {month_year(first)}, the last one in {month_year(last)}",
            (f"Reviewed {n_r} pull request{'s' if n_r != 1 else ''} by other people" if n_r else "No reviews of other people's work"),
            f"{linked} of the changes are linked to a task in the tracker",
        ]
        if own_prs[dev]:
            facts.append(f"{len(sent_back[dev])} of {own_prs[dev]} own pull requests were sent back for rework at least once")
        if areas:
            facts.append(f"Changes touch {len(areas)} different areas")
        profile = (f"Most changes are in the area{'s' if len(top) > 1 else ''} {join(top)}." if top
                   else "The records link few changes to a named area.")
        out.append({
            "id": dev,
            "label": dev,
            "role": f"{n_c} change{'s' if n_c != 1 else ''} · {n_r} review{'s' if n_r != 1 else ''} of other people's work",
            "tenure": f"active {month_year(first)} to {month_year(last)}",
            "profile": profile,
            "evidence": facts,
        })
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--project", required=True)
    a = ap.parse_args()
    project_cfg(load_config(), a.project)
    people = build(a.project)
    path = ensure_runs() / f"{a.project}_people.candidate.json"
    path.write_text(json.dumps({
        "project": a.project,
        "computed_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "people": people,
    }, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"{a.project}: {len(people)} people -> {path}")
    for p in people:
        print(" ", p["id"], p["role"], "|", p["profile"])


if __name__ == "__main__":
    main()
